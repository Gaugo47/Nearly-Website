import { copyFile, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve } from "node:path";

const source = resolve(process.argv[2] || "../Application-mobile-Nearly/docs/site-screenshots");
const refreshed = ["accueil", "carte", "compagnon", "idees", "moments", "party-expenses", "rituels"];
const screens = [...refreshed, "party", "party-lab", "party-photos", "spicy-home", "spicy-vault"];
// Validate the complete batch before replacing any public asset.
for (const screen of refreshed) {
  const bytes = await readFile(resolve(source, `app-${screen}.png`));
  if (bytes.subarray(0, 8).toString("hex") !== "89504e470d0a1a0a") throw new Error(`Invalid PNG: ${screen}`);
}
for (const screen of refreshed) await copyFile(resolve(source, `app-${screen}.png`), resolve(`public/media/app-${screen}.png`));
const versions = {};
for (const screen of screens) {
  const path = `/media/app-${screen}.png`;
  versions[path] = createHash("sha256").update(await readFile(resolve(`public${path}`))).digest("hex").slice(0, 12);
}
await writeFile("app/screenshot-versions.ts", `// Generated by npm run screenshots:sync.\nexport const screenshotVersions: Record<string, string> = ${JSON.stringify(versions, null, 2)};\n`);
console.log(`${refreshed.length} screenshots synchronized; ${screens.length} cache versions refreshed.`);
