import { copyFile, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve } from "node:path";

const source = resolve(process.argv[2] || "work/iphone-captures");
const screens = ["accueil", "amis", "famille", "carte", "compagnon", "idees", "moments", "party-expenses", "rituels", "party", "party-lab", "party-photos", "spicy-home", "spicy-vault"];
const refreshed = screens.filter(screen => screen !== "party-photos");
function imageSize(bytes) {
  if (bytes.readUInt16BE(0) !== 0xffd8) throw new Error("Expected a native JPEG capture");
  let offset = 2;
  while (offset < bytes.length) {
    while (bytes[offset] === 0xff) offset++;
    const marker = bytes[offset++];
    if (marker === 0xd9 || marker === 0xda) break;
    const length = bytes.readUInt16BE(offset);
    if ([0xc0, 0xc1, 0xc2].includes(marker)) return [bytes.readUInt16BE(offset + 5), bytes.readUInt16BE(offset + 3)];
    offset += length;
  }
  throw new Error("Missing JPEG dimensions");
}
// Validate the complete batch before replacing any public asset.
for (const screen of refreshed) {
  const [width, height] = imageSize(await readFile(resolve(source, `app-${screen}.jpg`)));
  if (width !== 393 || height !== 758) throw new Error(`Expected a 393×758 screenshot: ${screen}`);
}
for (const screen of refreshed) await copyFile(resolve(source, `app-${screen}.jpg`), resolve(`public/media/app-${screen}.jpg`));
const versions = {};
for (const screen of screens) {
  const path = `/media/app-${screen}.${screen === "party-photos" ? "png" : "jpg"}`;
  versions[path] = createHash("sha256").update(await readFile(resolve(`public${path}`))).digest("hex").slice(0, 12);
}
await writeFile("app/screenshot-versions.ts", `// Generated by npm run screenshots:sync.\nexport const screenshotVersions: Record<string, string> = ${JSON.stringify(versions, null, 2)};\n`);
console.log(`${refreshed.length} screenshots synchronized; ${screens.length} cache versions refreshed.`);
